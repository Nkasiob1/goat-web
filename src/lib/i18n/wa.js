// "2250701234567" -> "fr". Only used until the person picks a language themselves.
export function guessLang(phone) {
  const digits = String(phone || "").replace(/\D/g, "");
  const hit = COUNTRY_LANG.find(([code]) => digits.startsWith(code));
  return hit ? hit[1] : "en";
}

// w(lang) -> that language's words, with English as the safety net for anything missing
export function w(lang) {
  return { ...WA.en, ...(WA[lang] || {}) };
}